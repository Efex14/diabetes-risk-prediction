def mapped_selectbox(question, mapping, default, key):
    options = list(mapping.keys())
    answer = st.selectbox(question, options=options, index=options.index(default), key=key)
    return answer, mapping[answer]


def yes_no_question(question, text, mappings, default_key, key):
    default = text[default_key]
    return mapped_selectbox(question, mappings["yes_no"], default, key)


def add_summary(summary_rows, text, question, answer):
    summary_rows.append({
        text["summary_question"]: question,
        text["summary_answer"]: answer,
    })


